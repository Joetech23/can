<p>An office move is a project, not a day out with a van. Plan it like one and your team can log in on Monday as if nothing happened.</p>

<h2>3 months before</h2>
<ul>
    <li>Check your lease end date and any reinstatement obligations at the old site.</li>
    <li>Appoint one internal move lead who can make decisions.</li>
    <li>Book a survey so your mover can plan crews, vans and timing.</li>
</ul>

<h2>6 to 8 weeks before</h2>
<ul>
    <li>Agree a floor plan for the new office and number every desk.</li>
    <li>Book IT and telecoms: broadband installation often has the longest lead time.</li>
    <li>Ask both buildings about lift bookings, loading bays and insurance certificates.</li>
</ul>

<h2>2 weeks before</h2>
<ul>
    <li>Issue crates and labels; each person packs their own desk.</li>
    <li>Clear out archives and old furniture. We can arrange secure disposal and recycling.</li>
    <li>Update your address with clients, suppliers, Companies House and HMRC.</li>
</ul>

<h2>Move weekend</h2>
<ul>
    <li>Crews pack IT and furniture on Friday evening once the team has left.</li>
    <li>Everything is delivered and placed by desk number on Saturday.</li>
    <li>Your IT team reconnects on Sunday and tests before Monday morning.</li>
</ul>
