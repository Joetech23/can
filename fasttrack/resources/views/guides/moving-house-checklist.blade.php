<p>A smooth moving day is decided weeks before it happens. Work through this checklist and the day itself becomes the easy part.</p>

<h2>8 weeks before</h2>
<ul>
    <li>Get removal quotes and pick a provisional date. Fridays and month-ends book up first.</li>
    <li>Walk through every room and decide what you are not taking: sell, donate or book a clearance.</li>
    <li>If you rent, check your notice period and book an end-of-tenancy clean.</li>
</ul>

<h2>6 weeks before</h2>
<ul>
    <li>Book your survey so your quote can be fixed.</li>
    <li>Order boxes, tape and wardrobe cartons, or add packing to your booking.</li>
    <li>Start packing rooms you rarely use: lofts, garages, spare rooms.</li>
</ul>

<h2>4 weeks before</h2>
<ul>
    <li>Confirm your date and pay the deposit to secure the crew.</li>
    <li>Check parking at both addresses. Some councils need a suspension booked two weeks ahead.</li>
    <li>Arrange storage if your completion dates do not line up.</li>
</ul>

<h2>2 weeks before</h2>
<ul>
    <li>Redirect your post and update your address with your bank, employer, GP and DVLA.</li>
    <li>Tell utility, broadband and council tax providers your moving date.</li>
    <li>Use up frozen food and plan simple meals for the last few days.</li>
</ul>

<h2>The week of the move</h2>
<ul>
    <li>Pack everything except daily essentials. Label every box with the room it is going to.</li>
    <li>Defrost the freezer 24 hours before.</li>
    <li>Pack an <strong>essentials box</strong>: kettle, mugs, phone chargers, toilet roll, bedding, medication and documents. Keep it with you.</li>
</ul>

<h2>Moving day</h2>
<ul>
    <li>Take meter readings and photos at both properties.</li>
    <li>Walk your crew lead through anything fragile or valuable.</li>
    <li>Do a final sweep of every cupboard before the van leaves, then follow your move on <a href="{{ route('track') }}">Track my move</a>.</li>
</ul>
