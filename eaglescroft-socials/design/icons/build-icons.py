"""Embed every SVG in ui/ and social/ into icons.css as .i-<name> mask classes.

Chrome refuses CSS masks loaded from file:// URLs, so icons ship as data URIs.
Usage: python3 design/icons/build-icons.py   (re-run after adding an SVG)
"""
import pathlib, re, urllib.parse

here = pathlib.Path(__file__).parent
rules = ["/* Generated by build-icons.py. Use: <span class=\"ic i-zap\"></span> (takes currentColor). */",
         ".ic { display: inline-block; flex: none; width: 1em; height: 1em; background: currentColor;",
         "  -webkit-mask: var(--i) center / contain no-repeat; mask: var(--i) center / contain no-repeat; }"]
for svg in sorted(list(here.glob("ui/*.svg")) + list(here.glob("social/*.svg"))):
    s = svg.read_text()
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"<title>.*?</title>", "", s)
    s = s.replace("currentColor", "#000")
    s = " ".join(s.split())
    uri = "data:image/svg+xml," + urllib.parse.quote(s, safe=" =:/'\",.-")
    rules.append(f'.i-{svg.stem} {{ --i: url("{uri}"); }}'.replace('url("data', "url('data").replace('"); }', "'); }"))
(here / "icons.css").write_text("\n".join(rules) + "\n")
print(f"{len(rules) - 3} icons -> icons.css")
